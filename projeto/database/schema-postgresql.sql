
    create table area_estudo (
        id bigint generated by default as identity,
        nome varchar(100) not null,
        descricao varchar(500),
        primary key (id)
    );

    create table curso (
        ativo boolean not null,
        duracao_meses integer,
        idioma varchar(5) not null,
        id bigint generated by default as identity,
        instituicao_id bigint not null,
        nome varchar(100) not null,
        descricao varchar(500),
        tipo_intercambio varchar(255) not null check ((tipo_intercambio in ('GRADUACAO','POS_GRADUACAO','CURSO_IDIOMA','ENSINO_MEDIO','TRABALHO'))),
        primary key (id)
    );

    create table curso_modelo_tarefa (
        curso_id bigint not null,
        modelo_tarefa_id bigint not null,
        primary key (curso_id, modelo_tarefa_id)
    );

    create table insituicao (
        id bigint generated by default as identity,
        nome varchar(100) not null,
        descricao varchar(500),
        site_oficial varchar(500),
        primary key (id)
    );

    create table modelo_tarefa (
        ativo boolean not null,
        id bigint generated by default as identity,
        titulo varchar(200) not null,
        descricao varchar(400) not null,
        categoria varchar(255) not null check ((categoria in ('DOCUMENTACAO','IDIOMA','FINANCEIRO','INSCRICAO','OUTROS'))),
        primary key (id)
    );

    create table perfil_intercambio (
        nascimento date not null,
        user_id bigint not null,
        pais_residencia varchar(100) not null,
        nivel_escolaridade varchar(255) not null check ((nivel_escolaridade in ('ENSINO_FUNDAMENTAL','ENSINO_MEDIO','GRADUACAO','POS_GRADUACAO','MESTRADO','DOUTORADO'))),
        situacao_escolaridade varchar(255) not null check ((situacao_escolaridade in ('CURSANDO','CONCLUIDO','INTERROMPIDO'))),
        primary key (user_id)
    );

    create table perfil_nacionalidades (
        perfil_id bigint not null,
        nacionalidade varchar(100) not null,
        primary key (perfil_id, nacionalidade)
    );

    create table perfil_proficiencia_idioma (
        idioma varchar(5) not null,
        perfil_id bigint not null,
        nivel varchar(255) not null check ((nivel in ('A1','A2','B1','B2','C1','C2')))
    );

    create table plano_area_interesse (
        area_estudo_id bigint not null,
        plano_id bigint not null,
        primary key (area_estudo_id, plano_id)
    );

    create table plano_intercambio (
        depende_bolsa boolean,
        duracao_meses integer,
        inicio_previsto date,
        moeda varchar(3),
        orcamento_total numeric(14,2),
        valor_guardado numeric(14,2),
        aporte_mensal numeric(14,2),
        curso_id bigint,
        id bigint generated by default as identity,
        user_id bigint not null,
        titulo varchar(100) not null,
        status varchar(255) not null check ((status in ('RASCUNHO','EM_ANDAMENTO','CONCLUIDO','CANCELADO'))),
        tipo_intercambio varchar(255) not null check ((tipo_intercambio in ('GRADUACAO','POS_GRADUACAO','CURSO_IDIOMA','ENSINO_MEDIO','TRABALHO'))),
        primary key (id)
    );

    create table preparacoes_idioma (
        data_meta date not null,
        minutos_semanais_planejados integer not null,
        idioma varchar(5) not null,
        id bigint generated by default as identity,
        plano_intercambio bigint not null,
        nivel_alvo varchar(255) not null check ((nivel_alvo in ('A1','A2','B1','B2','C1','C2'))),
        status varchar(255) not null check ((status in ('NAO_INICIADA','EM_ANDAMENTO','CONCLUIDA'))),
        primary key (id)
    );

    create table tarefa_plano (
        anotacoes varchar(10000),
        anotacoes_atualizadas_em timestamp(6) with time zone,
        prazo date,
        concluida_em timestamp(6) with time zone,
        id bigint generated by default as identity,
        modelo_origem_id bigint,
        categoria varchar(32),
        tema varchar(32),
        chave_sugestao varchar(80),
        plano_id bigint not null,
        titulo varchar(200) not null,
        descricao varchar(400) not null,
        status varchar(255) not null check ((status in ('PENDENTE','EM_ANDAMENTO','CONCLUIDA'))),
        primary key (id),
        constraint uk_tarefa_plano_modelo unique (plano_id, modelo_origem_id),
        constraint uk_tarefa_plano_sugestao unique (plano_id, chave_sugestao)
    );

    create table users (
        active boolean not null,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        role varchar(20) not null check ((role in ('USER','ADMIN'))),
        nome varchar(100) not null,
        email varchar(254) not null unique,
        password_hash varchar(255) not null,
        primary key (id)
    );

